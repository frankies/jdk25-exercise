  /**
   * Prints the dimensions and area of a supported shape.
   *
   * @param w shape to calculate and display
   */
  private void calc(Shape w) {
    switch (w) {
    case Circle c -> IO.println("Circle radius: " + c.radius() + " area: " + c.area());
    case Square c -> IO.println("Square side: " + c.side() + " area: " + c.area());
    default -> IO.println("Unknown shape");
    }
  }

  /**
   * A shape whose area can be calculated.
   */
  sealed interface Shape permits Circle, Square, Triangle {
    /**
     * Returns the area of this shape.
     *
     * @return the area
     */
    double area();
  }

  /**
   * A circle represented by its radius.
   *
   * @param radius circle radius
   */
  record Circle(double radius) implements Shape {

    public Circle {
       assert radius > 0 : "Must be positive"; 
    }

    /**
     * Calculates the circle's area.
     *
     * @return the area
     */
    @Override
    public double area() {
      return Math.PI * radius * radius;
    }
  }

  /**
   * A square represented by its side length.
   *
   * @param side square side length
   */
  record Square(double side) implements Shape {
    /**
     * Calculates the square's area.
     *
     * @return the area
     */
    @Override
    public double area() {
      return side * side;
    }
  }

  /**
   * A triangle represented by its base and height.
   *
   * @param base triangle base length
   * @param height triangle height
   */
  record Triangle(double base, double height) implements Shape {
    /**
     * Calculates the triangle's area.
     *
     * @return the area
     */
    @Override
    public double area() {
      return 0.5 * base * height;
    }
  }

