  /**
   * A sealed type hierarchy for exhaustive switch examples.
   */
  sealed interface S permits A, B, C {
  }

  /** One permitted implementation of {@link S}. */
  final class A implements S {
  }

  /** One permitted implementation of {@link S}. */
  final class B implements S {
  }

  /** One permitted implementation of {@link S}. */
  record C(int i) implements S {
  }

  /**
   * Returns a distinct value for each permitted implementation of {@link S}.
   *
   * @param s value to match
   * @return the value associated with its implementation
   */
  static int testSealedExhaustive(S s) {
    return switch (s) {
    case A _ -> 1;
    case B _ -> 2;
    case C _ -> 3;
    };
  }
  
