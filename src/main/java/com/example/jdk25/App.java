  /**
   * Generic sealed hierarchy used to demonstrate exhaustive generic pattern matching.
   *
   * @param <T> value type represented by the hierarchy
   */
  sealed interface I<T> permits D, E {}

  /** A permitted implementation that always represents {@link String}. */
  final class D<X> implements I<String> {}

  /** A permitted implementation that preserves its type parameter. */
  final class E<Y> implements I<Y> {}

  /**
   * Matches the only possible implementation of {@code I<Integer>}.
   *
   * @param i value to match
   * @return the example result
   */
  static int testGenericSealedExhaustive(I<Integer> i) {
      return switch (i) {
          // Exhaustive as no D case possible!
          case E<Integer> _ -> 42;
      };
  }
